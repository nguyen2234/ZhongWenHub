/**
 * Builds the today's review queue with predicted interval labels
 */
export function getDueReviewQueue(): ReviewQueueItem[] {
  const dueItems: ReviewQueueItem[] = [];

  for (const vocab of INITIAL_VOCABULARY_LIST) {
    const userState = INITIAL_USER_VOCAB_STATES[vocab.id];
    if (userState && userState.isDueToday) {
      const srsState = INITIAL_SRS_STATES[vocab.id] || {
        vocabularyId: vocab.id,
        stability: 1,
        difficulty: 4,
        interval: 1,
        repetitions: 1,
        easeFactor: 2.5,
      };
      dueItems.push({
        vocabulary: vocab,
        userState,
        srsState,
        predictedIntervals: predictIntervalLabels(srsState),
      });
    }
  }

  return dueItems;
}
