def generate_vocabulary_examples():
    conn_str = "Driver={ODBC Driver 17 for SQL Server};Server=.\\SQLEXPRESS;Database=ZhongWenHub_Dev;Trusted_Connection=yes;"
    conn = pyodbc.connect(conn_str)
    cursor = conn.cursor()

    # Query all 291 HSK 1 missing vocabularies
    query = """
    SELECT Id, LessonId, Hanzi, Pinyin, MeaningVi, PartOfSpeech
    FROM vocabularies
    WHERE HskLevel = 1 AND (ExamplesJson IS NULL OR LEN(LTRIM(RTRIM(ExamplesJson))) <= 5)
    ORDER BY LessonId, Hanzi
    """
    cursor.execute(query)
    rows = cursor.fetchall()
    print(f"Total missing vocabulary rows fetched: {len(rows)}")

    staging_entries = []
    missing_mapping = []

    for r in rows:
        v_id = str(r[0])
        lesson_id = str(r[1])
        hanzi = str(r[2]).strip()
        pinyin = str(r[3]).strip() if r[3] else ""
        meaning_vi = str(r[4]).strip() if r[4] else ""
        pos = str(r[5]).strip() if r[5] else ""

        if hanzi in HSK1_EXAMPLES_MAP:
            zh, py, vi = HSK1_EXAMPLES_MAP[hanzi]
        else:
            # Fallback natural template if word has specific meaning
            zh = f"这是{hanzi}。"
            py = f"Zhè shì {pinyin}."
            vi = f"Đây là {meaning_vi}."
            missing_mapping.append(hanzi)

        # Ensure target hanzi is present in the example sentence
        if hanzi not in zh:
            print(f"WARNING: Hanzi '{hanzi}' not found in sentence: '{zh}'")

        example_obj = [{
            "zh": zh,
            "pinyin": py,
            "meaningVi": vi
        }]

        entry = {
            "vocabularyId": v_id,
            "lessonId": lesson_id,
            "hskLevel": 1,
            "hanzi": hanzi,
            "pinyin": pinyin,
            "meaningVi": meaning_vi,
            "partOfSpeech": pos,
            "examples": example_obj,
            "examplesJson": json.dumps(example_obj, ensure_ascii=False),
            "status": "AI_ASSISTED_UNVERIFIED",
            "qaNotes": f"HSK 1 standard beginner sentence for '{hanzi}' ({pinyin})"
        }
        staging_entries.append(entry)

    conn.close()

    if missing_mapping:
        print(f"Fallback generated for {len(missing_mapping)} words: {missing_mapping}")
    else:
        print("ALL 291 vocabularies mapped to handcrafted authentic beginner sentences!")

    out_file = Path("data/hsk30/staging/hsk1_vocabulary_examples.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(staging_entries, f, ensure_ascii=False, indent=2)

    print(f"Successfully wrote {len(staging_entries)} staging vocabulary example records to {out_file}")
    return len(staging_entries)

if __name__ == "__main__":
    count = generate_vocabulary_examples()
    sys.exit(0 if count == 291 else 1)
